// Sprache des Betriebs = Cockpit-Sprache des Inhabers (users.sprache).
export async function betriebSprache(db, tenantId) {
  if (!tenantId) return 'de';
  try {
    const { data } = await db.from('users').select('sprache').eq('tenant_id', tenantId).not('sprache', 'is', null).limit(1);
    return sprache(data && data[0] && data[0].sprache);
  } catch { return 'de'; }
}
